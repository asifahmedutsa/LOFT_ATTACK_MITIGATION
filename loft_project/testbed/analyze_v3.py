"""Preregistered analysis of the v3 T1 campaign (results/testbed_prereg_v3/preregistration.json).

H1 benign_harmed_pct, H2 attack_share_avg_pct_s11: ensguard vs each of 8 comparators over the 15
paired attack runs (A2 / A4 / E9P x seeds 4120-4124), one-sided exact sign test, a tie counts
against the hypothesis, Holm over the 8. H3 and H4 descriptive on ensguard's runs.

    python3 testbed/analyze_v3.py      # writes results/testbed_prereg_v3/{runs.csv, hypotheses.csv, report.md}
"""
import csv
import glob
import json
import os
import re
from math import comb

R = os.path.expanduser("~/loft-runs")
OUT = "results/testbed_prereg_v3"
PRE = json.load(open(os.path.join(OUT, "preregistration.json")))
SEEDS = [str(s) for s in PRE["seeds"]]
ATTACKS = ["A2", "A4", "E9P"]
NAME = {"dualguard+portguard+hostid": "dualguard-portguard-hostid"}
DEFS = [NAME.get(d, d) for d in PRE["cells"]["defenses"]]
COMP = [d for d in DEFS if d not in ("none", "ensguard")]
KEYS = ["benign_harmed_pct", "attack_share_avg_pct_s11", "attack_share_avg_pct_s12",
        "attack_share_avg_pct_s13", "benign_packet_in_lost_pct", "probe_post_success_pct",
        "hosts_blocked_attack", "hosts_blocked_benign", "first_attack_block_s"]


def summary(path):
    d = {}
    for line in open(path):
        m = re.match(r"\s+(\S+)\s+(.+?)\s*$", line)
        if m:
            try:
                d[m[1]] = float(m[2])
            except ValueError:
                d[m[1]] = m[2]
    return d


def sign_p(wins, n):
    """One-sided exact sign test: P(X >= wins), X ~ Bin(n, 1/2); ties are losses."""
    return sum(comb(n, k) for k in range(wins, n + 1)) / 2 ** n


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, (len(ps) - rank) * ps[i])
        adj[i] = min(1.0, run)
    return adj


runs = {}
for v in ATTACKS + ["benign"]:
    for d in DEFS:
        for s in SEEDS:
            p = f"{R}/v3_T1_{v}_{d}_s{s}/summary.txt"
            runs[(v, d, s)] = summary(p)
missing = [k for k, r in runs.items() if "benign_harmed_pct" not in r]
assert not missing, missing

os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "runs.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["variant", "defense", "seed"] + KEYS)
    for (v, d, s), r in sorted(runs.items()):
        w.writerow([v, d, s] + [r.get(k, "") for k in KEYS])

hyp = []
for h, key in (("H1", "benign_harmed_pct"), ("H2", "attack_share_avg_pct_s11")):
    rows = []
    for c in COMP:
        pairs = [(runs[(v, "ensguard", s)][key], runs[(v, c, s)][key]) for v in ATTACKS for s in SEEDS]
        wins = sum(e < o for e, o in pairs)
        ties = sum(e == o for e, o in pairs)
        rows.append(dict(hypothesis=h, comparator=c, n=len(pairs), wins=wins, ties=ties,
                         ens_mean=sum(e for e, _ in pairs) / len(pairs),
                         comp_mean=sum(o for _, o in pairs) / len(pairs), p=sign_p(wins, len(pairs))))
    for r, a in zip(rows, holm([r["p"] for r in rows])):
        r["p_holm"] = a
        r["supported"] = a < 0.05
    hyp += rows
with open(os.path.join(OUT, "hypotheses.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(hyp[0]))
    w.writeheader()
    w.writerows(hyp)

ben = [runs[("benign", "ensguard", s)] for s in SEEDS]
h3_harm = sum(r["benign_harmed_pct"] for r in ben) / len(ben)
h3_lost = sum(r["benign_packet_in_lost_pct"] for r in ben) / len(ben)
h4 = [(v, s, int(runs[(v, "ensguard", s)].get("hosts_blocked_benign", 0)))
      for v in ATTACKS + ["benign"] for s in SEEDS]
h4_bad = [x for x in h4 if x[2] > 0]

L = ["# Preregistered analysis, v3 T1 campaign", "",
     "Generated by `testbed/analyze_v3.py` from the 200 runs in `~/loft-runs/v3_T1_*` "
     "(seeds " + ", ".join(SEEDS) + "). Test: one-sided exact sign test over 15 paired attack runs, "
     "ties count against, Holm over the 8 comparators, alpha 0.05.", ""]
for h, label in (("H1", "benign harm (%)"), ("H2", "attack share of the core table s11 (%)")):
    L += [f"## {h}: ensguard lower {label} than each comparator", "",
          "| Comparator | Wins / 15 | Ties | ensguard mean | comparator mean | p | p (Holm) | Supported |",
          "|---|---|---|---|---|---|---|---|"]
    for r in (x for x in hyp if x["hypothesis"] == h):
        L.append(f"| {r['comparator']} | {r['wins']} | {r['ties']} | {r['ens_mean']:.2f} | "
                 f"{r['comp_mean']:.2f} | {r['p']:.4f} | {r['p_holm']:.4f} | "
                 f"{'yes' if r['supported'] else 'no'} |")
    L.append("")
L += ["## H3: benign-only runs", "",
      f"- mean benign harm {h3_harm:.2f} % (bar 0.5 %): {'pass' if h3_harm <= 0.5 else 'fail'}",
      f"- mean lost first packets {h3_lost:.2f} % (bar 1 %): {'pass' if h3_lost <= 1 else 'fail'}", "",
      "## H4: no benign host blocked in ensguard's 20 runs", "",
      f"- benign hosts blocked in {len(h4_bad)} of 20 runs: {'pass' if not h4_bad else 'fail'}"]
L += [f"  - {v}, seed {s}: {n} host(s)" for v, s, n in h4_bad]
L += ["", "## Means per variant and defense (5 seeds)", "",
      "| Variant | Defense | harm % | attack share s11 % | lost first pkts % | probe success % |",
      "|---|---|---|---|---|---|"]
for v in ATTACKS + ["benign"]:
    for d in DEFS:
        rs = [runs[(v, d, s)] for s in SEEDS]
        m = [sum(r.get(k, 0) for r in rs) / len(rs) for k in
             ("benign_harmed_pct", "attack_share_avg_pct_s11", "benign_packet_in_lost_pct",
              "probe_post_success_pct")]
        L.append(f"| {v} | {d} | " + " | ".join(f"{x:.2f}" for x in m) + " |")
open(os.path.join(OUT, "report.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
