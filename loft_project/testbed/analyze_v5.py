"""Preregistered analysis of the v5 campaign (results/testbed_prereg_v5/preregistration.json).

H1 harm, H2 attack share at s11: ensguard-v5 vs dms-btt and ftmaster (Holm over the 2); H3 harm
and H4 decision time vs ensguard v3; H8 attack share vs ensguard-v4lite. Each: one-sided exact
sign test over the 15 paired attack runs (A2, A4, E9P x 5 seeds), a tie counts against. H5, H6
descriptive; H7 the probe guard (a pair fails when v5 is > 5 points below v3; fails at >= 8).

    python3 testbed/analyze_v5.py      # writes results/testbed_prereg_v5/{runs.csv, hypotheses.csv, report.md}
"""
import csv
import json
import os
import re
from math import comb

R = os.path.expanduser("~/loft-runs")
OUT = "results/testbed_prereg_v5"
PRE = json.load(open(os.path.join(OUT, "preregistration.json")))
SEEDS = [str(s) for s in PRE["seeds"]]
ATTACKS = ["A2", "A4", "E9P"]
DEFS = PRE["cells"]["defenses"]
V5 = "ensguard-v5"
KEYS = ["benign_harmed_pct", "attack_share_avg_pct_s11", "attack_share_max_pct_s11", "benign_packet_in_lost_pct",
        "benign_dropped_by_rule_pct", "probe_post_success_pct", "probe_post_connect_ms_median",
        "hosts_blocked_attack", "hosts_blocked_benign", "first_attack_block_s", "decision_ms_mean",
        "packet_in", "table_full_s11", "overflow_s_post_s11"]


def summary(path):
    d = {}
    for line in open(path):
        m = re.match(r"\s+(\S+)\s+(.+?)\s*$", line)
        if not m:
            continue
        k, v = m[1], m[2]
        if k == "decision_ms":
            d["decision_ms_mean"] = float(re.match(r"mean (\S+),", v)[1])
            continue
        try:
            d[k] = float(v)
        except ValueError:
            d[k] = v
    for k in ("hosts_blocked_attack", "hosts_blocked_benign"):
        d.setdefault(k, 0.0)            # written only when a host was blocked
    return d


def sign_p(wins, n):
    return sum(comb(n, k) for k in range(wins, n + 1)) / 2 ** n


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, (len(ps) - rank) * ps[i])
        adj[i] = min(1.0, run)
    return adj


runs = {}
for v in ATTACKS + ["benign"]:
    for d in DEFS:
        for s in SEEDS:
            runs[(v, d, s)] = summary(f"{R}/v5_T1B_{v}_{d}_s{s}/summary.txt")
missing = [k for k, r in runs.items() if "benign_harmed_pct" not in r]
assert not missing, missing

os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "runs.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["variant", "defense", "seed"] + KEYS)
    for (v, d, s), r in sorted(runs.items()):
        w.writerow([v, d, s] + [r.get(k, "") for k in KEYS])


def test(h, key, comps):
    rows = []
    for c in comps:
        pairs = [(runs[(v, V5, s)][key], runs[(v, c, s)][key]) for v in ATTACKS for s in SEEDS]
        wins = sum(e < o for e, o in pairs)
        rows.append(dict(hypothesis=h, measure=key, comparator=c, n=len(pairs), wins=wins,
                         ties=sum(e == o for e, o in pairs), v5_mean=sum(e for e, _ in pairs) / len(pairs),
                         comp_mean=sum(o for _, o in pairs) / len(pairs), p=sign_p(wins, len(pairs))))
    for r, a in zip(rows, holm([r["p"] for r in rows])):
        r["p_holm"], r["supported"] = a, a < 0.05
    return rows


hyp = (test("H1", "benign_harmed_pct", ["dms-btt", "ftmaster"])
       + test("H2", "attack_share_avg_pct_s11", ["dms-btt", "ftmaster"])
       + test("H3", "benign_harmed_pct", ["ensguard"])
       + test("H4", "decision_ms_mean", ["ensguard"])
       + test("H8", "attack_share_avg_pct_s11", ["ensguard-v4lite"]))
with open(os.path.join(OUT, "hypotheses.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(hyp[0]))
    w.writeheader()
    w.writerows(hyp)

h5 = [(v, s, int(runs[(v, V5, s)]["hosts_blocked_benign"])) for v in ATTACKS + ["benign"] for s in SEEDS]
h5_bad = [x for x in h5 if x[2] > 0]
ben = [runs[("benign", V5, s)] for s in SEEDS]
h6_harm = sum(r["benign_harmed_pct"] for r in ben) / len(ben)
h6_lost = sum(r["benign_packet_in_lost_pct"] for r in ben) / len(ben)
h7_fail = sum(runs[(v, V5, s)]["probe_post_success_pct"] < runs[(v, "ensguard", s)]["probe_post_success_pct"] - 5
              for v in ATTACKS for s in SEEDS)

L = ["# Preregistered analysis, v5 campaign (T1B)", "",
     "Generated by `testbed/analyze_v5.py` from the 120 runs in `~/loft-runs/v5_T1B_*` (seeds " + ", ".join(SEEDS) +
     "). One-sided exact sign test over 15 paired attack runs, ties count against, Holm over the comparators "
     "of each hypothesis, alpha 0.05.", "",
     "| Hypothesis | Measure | Comparator | Wins / 15 | Ties | v5 mean | comparator mean | p | p (Holm) | Supported |",
     "|---|---|---|---|---|---|---|---|---|---|"]
for r in hyp:
    L.append(f"| {r['hypothesis']} | {r['measure']} | {r['comparator']} | {r['wins']} | {r['ties']} | {r['v5_mean']:.2f} | "
             f"{r['comp_mean']:.2f} | {r['p']:.4f} | {r['p_holm']:.4f} | {'yes' if r['supported'] else 'no'} |")
L += ["", f"- **H5** no benign host blocked in ensguard-v5's 20 runs: {'pass' if not h5_bad else 'fail'} "
      f"({len(h5_bad)} runs with a benign block)"]
L += [f"  - {v}, seed {s}: {n} host(s)" for v, s, n in h5_bad]
L += [f"- **H6** benign-only runs: mean harm {h6_harm:.2f} % (bar 0.5), mean lost first packets {h6_lost:.2f} % (bar 1): "
      f"{'pass' if h6_harm <= 0.5 and h6_lost <= 1 else 'fail'}",
      f"- **H7** probe guard: {h7_fail} of 15 pairs more than 5 points below v3 (fails at 8): {'pass' if h7_fail < 8 else 'fail'}",
      "", "## Means per variant and defense (5 seeds)", "",
      "| Variant | Defense | harm % | attack share s11 % | max share % | lost first pkts % | dropped by rule % | "
      "probe success % | decision ms | attackers blocked | benign blocked |",
      "|---|---|---|---|---|---|---|---|---|---|---|"]
for v in ATTACKS + ["benign"]:
    for d in DEFS:
        rs = [runs[(v, d, s)] for s in SEEDS]
        m = [sum(float(r.get(k, 0) or 0) for r in rs) / len(rs) for k in
             ("benign_harmed_pct", "attack_share_avg_pct_s11", "attack_share_max_pct_s11", "benign_packet_in_lost_pct",
              "benign_dropped_by_rule_pct", "probe_post_success_pct", "decision_ms_mean", "hosts_blocked_attack",
              "hosts_blocked_benign")]
        L.append(f"| {v} | {d} | " + " | ".join(f"{x:.2f}" for x in m) + " |")
open(os.path.join(OUT, "report.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
